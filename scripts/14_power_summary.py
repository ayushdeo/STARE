"""
Multiplicity-adjusted, cluster-aware summary of every paired margin (revision, reviewer point 5).

Walks the experiment JSONs (05 graphflow, 09, 10, 12, 13), collects every paired-margin summary
(any dict with mean / ci95 / per_slide), and reports for each: n slides, n study clusters, mean,
slide-level CI, study-cluster CI, tissue-stratified mean + CI, the cluster-level sign-flip p, and its
Holm adjustment (a) within the experiment and (b) across all experiments. If results/n7_legacy/ holds
the original 7-slide JSONs, their mean and CI are shown alongside for the same margin.

Local, no data needed (reads JSONs only).  Run:  python -u scripts/14_power_summary.py
Writes results/power_summary.json and docs/POWER_SUMMARY.md.
"""
import os, sys, json
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))
from pathlib import Path
import numpy as np
from stare import config, stats

FILES = ["ci_multislide_graphflow.json", "realdata_detection.json", "competitors.json",
         "hvg_sensitivity.json", "batched_contiguous.json"]
LEGACY_DIR = Path(config.RESULTS_ROOT) / "n7_legacy"
# Pre-specified PRIMARY family (the paper's claims); everything else is secondary/sensitivity.
#   reconstruction headline: adaptive vs best non-adaptive (05, graphflow), every budget
#   detection claim: value_greedy vs best coverage on detection (09), and its realism checks (13)
PRIMARY = [("ci_multislide_graphflow", "/ours_vs_best_nonadapt"),
           ("realdata_detection", "/value_greedy_detect_vs_bestcover"),
           ("realdata_detection", "/value_greedy_recon_vs_bestcover"),
           ("batched_contiguous", "")]


def is_primary(exp, name):
    return any(exp == e and (s == "" or name.endswith(s)) for e, s in PRIMARY)


def min_attainable_p(n_clusters):
    """Smallest two-sided exact sign-flip p with k clusters: 2 / 2^k."""
    return 2.0 / 2 ** n_clusters if n_clusters else float("nan")


def margins(obj, path=""):
    if isinstance(obj, dict):
        if {"mean", "ci95", "per_slide"} <= set(obj):
            yield path.strip("/"), obj
            return
        for k, v in obj.items():
            if k in ("per_slide", "grouping"):
                continue
            yield from margins(v, f"{path}/{k}")


def p_of(m, grouping):
    """Exact cluster-level sign-flip p, recomputed from the stored per-slide margins (unrounded; the
    JSONs from the 4070 run stored a 4-decimal Monte Carlo value, which rounds small p to 0)."""
    cl = (grouping or {}).get("clusters")
    return stats.signflip_p(np.asarray(m["per_slide"], float), cl)


def main():
    res = Path(config.RESULTS_ROOT)
    rows = []
    for f in FILES:
        p = res / f
        if not p.exists():
            print(f"[skip] {p} missing"); continue
        d = json.loads(p.read_text(encoding="utf-8"))
        legacy = {}
        if (LEGACY_DIR / f).exists():
            legacy = dict(margins(json.loads((LEGACY_DIR / f).read_text(encoding="utf-8"))))
        fam = []
        for name, m in margins(d):
            r = {"experiment": f.replace(".json", ""), "margin": name, "n": m["n_slides"],
                 "n_clusters": m.get("n_clusters"), "mean": m["mean"], "ci95": m["ci95"],
                 "cluster_ci95": m.get("cluster_ci95"), "stratified_mean": m.get("stratified_mean"),
                 "stratified_ci95": m.get("stratified_ci95"), "by_stratum": m.get("by_stratum"),
                 "signflip_p": p_of(m, d.get("grouping"))}
            if name in legacy:
                r["n7_mean"], r["n7_ci95"] = legacy[name]["mean"], legacy[name]["ci95"]
            fam.append(r)
        for r, h in zip(fam, stats.holm([r["signflip_p"] for r in fam])):
            r["holm_p_within_experiment"] = h
        rows += fam
    for r, h in zip(rows, stats.holm([r["signflip_p"] for r in rows])):
        r["holm_p_all"] = h
    prim = [r for r in rows if is_primary(r["experiment"], r["margin"])]
    for r, h in zip(prim, stats.holm([r["signflip_p"] for r in prim])):
        r["primary"], r["holm_p_primary"] = True, h
    k = max((r["n_clusters"] or r["n"]) for r in rows) if rows else 0
    floor = {"max_clusters": k, "min_attainable_p": min_attainable_p(k),
             "holm_threshold_primary": 0.05 / max(len(prim), 1), "n_primary": len(prim),
             "holm_threshold_all": 0.05 / max(len(rows), 1), "n_all": len(rows)}

    out = res / "power_summary.json"
    out.write_text(json.dumps({"n_margins": len(rows), "power_floor": floor, "rows": rows}, indent=2), encoding="utf-8")

    fmt = lambda c: "--" if not c else f"[{c[0]:+.3f}, {c[1]:+.3f}]"
    lines = ["# Power summary (generated by scripts/14_power_summary.py — do not edit by hand)", "",
             "Margin = adaptive minus best coverage baseline (or as named). `p` = cluster-level sign-flip "
             "test (study clusters); Holm-adjusted within each experiment and across all margins. "
             "Cluster CI resamples whole studies; stratified = equal-weight mean over tissues. "
             "**P** marks the pre-specified primary family (Holm (primary) column).", "",
             f"Power floor: with {floor['max_clusters']} independent units the smallest attainable exact p is "
             f"{floor['min_attainable_p']:.2g}; Holm needs p < {floor['holm_threshold_primary']:.2g} for the smallest "
             f"primary p ({floor['n_primary']} primary margins) and < {floor['holm_threshold_all']:.2g} across all "
             f"{floor['n_all']}.", ""]
    for exp in dict.fromkeys(r["experiment"] for r in rows):
        lines += [f"## {exp}", "",
                  "| margin | n (clusters) | mean | slide CI | cluster CI | stratified | p | Holm (exp) | Holm (primary) | Holm (all) | n=7 mean, CI |",
                  "|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in [r for r in rows if r["experiment"] == exp]:
            n7 = f"{r['n7_mean']:+.3f} {fmt(r['n7_ci95'])}" if "n7_mean" in r else "--"
            strat = "--" if r["stratified_mean"] is None else f"{r['stratified_mean']:+.3f} {fmt(r['stratified_ci95'])}"
            hp = f"{r['holm_p_primary']:.2g}" if r.get("primary") else "--"
            lines.append(f"| {'**P** ' if r.get('primary') else ''}{r['margin']} | {r['n']} ({r['n_clusters'] or '--'}) | {r['mean']:+.3f} | {fmt(r['ci95'])} | "
                         f"{fmt(r['cluster_ci95'])} | {strat} | {r['signflip_p']:.2g} | {r['holm_p_within_experiment']:.2g} | "
                         f"{hp} | {r['holm_p_all']:.2g} | {n7} |")
        lines.append("")
    md = Path("docs") / "POWER_SUMMARY.md"
    md.parent.mkdir(exist_ok=True)
    md.write_text("\n".join(lines), encoding="utf-8")
    print(f"[write] {out}\n[write] {md}  ({len(rows)} margins, {len(prim)} primary)")
    print(f"[power floor] {floor}")
    for r in prim:
        star = "*" if r["holm_p_primary"] < 0.05 else " "
        print(f"  {r['experiment'][:18]:18s} {r['margin'][:52]:52s} {r['mean']:+.3f} p={r['signflip_p']:.2g} "
              f"holm_primary={r['holm_p_primary']:.2g}{star}")


if __name__ == "__main__":
    main()
